#!/usr/bin/env python3
"""Convert ASCII-art icons into LVGL 9 alpha (A8) bitmaps.

Input:  main/assets/icons/<name>.txt, 24 columns x 24 rows, '#' = lit.
Output: main/assets/icons.c and main/assets/icons.h with one
        `const lv_image_dsc_t icon_<name>` per file, scaled by SCALE.

Run from the firmware directory:  python3 tools/gen_icons.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ART_SIZE = 24
SCALE = 4          # 24 -> 96 pixels on the 368x448 panel
HERE = Path(__file__).resolve().parent
ICON_DIR = HERE.parent / "main" / "assets" / "icons"
OUT_C = HERE.parent / "main" / "assets" / "icons.c"
OUT_H = HERE.parent / "main" / "assets" / "icons.h"


def load_art(path: Path) -> list[str]:
    rows = [ln.rstrip("\n") for ln in path.read_text().splitlines()]
    rows = [r for r in rows if r.strip() != ""]
    if len(rows) != ART_SIZE or any(len(r) != ART_SIZE for r in rows):
        raise SystemExit(f"{path.name}: expected {ART_SIZE} rows of {ART_SIZE} chars, "
                         f"got {len(rows)} rows: {[len(r) for r in rows]}")
    return rows


def to_a8(rows: list[str]) -> bytes:
    size = ART_SIZE * SCALE
    out = bytearray(size * size)
    for y in range(size):
        src_row = rows[y // SCALE]
        for x in range(size):
            out[y * size + x] = 0xFF if src_row[x // SCALE] == "#" else 0x00
    return bytes(out)


def c_array(data: bytes, per_line: int = 32) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def main() -> None:
    files = sorted(ICON_DIR.glob("*.txt"))
    if not files:
        raise SystemExit(f"no icons in {ICON_DIR}")
    size = ART_SIZE * SCALE
    c_parts = [
        "/* Generated by tools/gen_icons.py. Do not edit; edit the .txt art instead. */",
        '#include "icons.h"',
        "",
    ]
    h_parts = [
        "/* Generated by tools/gen_icons.py. Do not edit. */",
        "#pragma once",
        '#include "lvgl.h"',
        "",
        f"#define ICON_SIZE {size}",
        "",
    ]
    for path in files:
        name = path.stem
        data = to_a8(load_art(path))
        c_parts.append(f"static const uint8_t icon_{name}_map[] = {{")
        c_parts.append(c_array(data))
        c_parts.append("};")
        c_parts.append(f"const lv_image_dsc_t icon_{name} = {{")
        c_parts.append("    .header = {")
        c_parts.append("        .magic = LV_IMAGE_HEADER_MAGIC,")
        c_parts.append("        .cf = LV_COLOR_FORMAT_A8,")
        c_parts.append("        .flags = 0,")
        c_parts.append(f"        .w = {size},")
        c_parts.append(f"        .h = {size},")
        c_parts.append(f"        .stride = {size},")
        c_parts.append("    },")
        c_parts.append(f"    .data_size = sizeof(icon_{name}_map),")
        c_parts.append(f"    .data = icon_{name}_map,")
        c_parts.append("};")
        c_parts.append("")
        h_parts.append(f"extern const lv_image_dsc_t icon_{name};")
        print(f"{name:12s} -> icon_{name} ({size}x{size})")
    OUT_C.write_text("\n".join(c_parts) + "\n")
    OUT_H.write_text("\n".join(h_parts) + "\n")
    print(f"wrote {OUT_C.relative_to(HERE.parent)} and {OUT_H.relative_to(HERE.parent)}")


if __name__ == "__main__":
    sys.exit(main())
