#!/usr/bin/env python3
"""Pixel-double an LVGL 1-bit bitmap font.

The launcher and lists use a chunky pixel font in the MonoUI spirit. LVGL
ships `unscii_16` (8x16 pixels per glyph); on the 368x448 panel that is too
small for a title, so this script reads LVGL's generated C file and writes a
2x version: every glyph pixel becomes a 2x2 block, giving a 16x32 font.

    python3 tools/gen_font2x.py \
        managed_components/lvgl__lvgl/src/font/lv_font_unscii_16.c \
        main/fonts/mono_font_32.c mono_font_32

The output is committed, so this only needs re-running if LVGL's font changes.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def parse_c_array(src: str, name: str) -> list[int]:
    m = re.search(rf"{name}\[\]\s*=\s*\{{(.*?)\}};", src, re.S)
    if not m:
        raise SystemExit(f"array {name} not found")
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(tok, 16) for tok in re.findall(r"0x[0-9a-fA-F]+", body)]


def parse_glyph_dsc(src: str) -> list[dict[str, int]]:
    m = re.search(r"glyph_dsc\[\]\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("glyph_dsc not found")
    glyphs = []
    for entry in re.finditer(r"\{([^{}]*)\}", m.group(1)):
        fields = dict(re.findall(r"\.(\w+)\s*=\s*(-?\d+)", entry.group(1)))
        glyphs.append({k: int(v) for k, v in fields.items()})
    return glyphs


def parse_cmap(src: str) -> tuple[int, int, int]:
    m = re.search(r"\.range_start\s*=\s*(\d+),\s*\.range_length\s*=\s*(\d+),\s*\.glyph_id_start\s*=\s*(\d+)", src)
    if not m:
        raise SystemExit("cmap not found")
    return int(m.group(1)), int(m.group(2)), int(m.group(3))


def parse_int(src: str, field: str) -> int:
    m = re.search(rf"\.{field}\s*=\s*(-?\d+)", src)
    return int(m.group(1)) if m else 0


class BitWriter:
    def __init__(self) -> None:
        self.bytes = bytearray()
        self.nbits = 0

    def put(self, bit: int) -> None:
        if self.nbits % 8 == 0:
            self.bytes.append(0)
        if bit:
            self.bytes[-1] |= 0x80 >> (self.nbits % 8)
        self.nbits += 1

    def align(self) -> None:
        self.nbits = len(self.bytes) * 8


def glyph_bits(bitmap: list[int], index: int, w: int, h: int) -> list[list[int]]:
    rows, bit = [], 0
    for _ in range(h):
        row = []
        for _ in range(w):
            byte = bitmap[index + bit // 8]
            row.append((byte >> (7 - bit % 8)) & 1)
            bit += 1
        rows.append(row)
    return rows


def main(argv: list[str]) -> None:
    if len(argv) != 4:
        raise SystemExit(__doc__)
    src_path, out_path, name = Path(argv[1]), Path(argv[2]), argv[3]
    src = src_path.read_text()
    bitmap = parse_c_array(src, "glyph_bitmap")
    glyphs = parse_glyph_dsc(src)
    range_start, range_length, glyph_id_start = parse_cmap(src)
    line_height = parse_int(src, "line_height")
    base_line = parse_int(src, "base_line")

    writer = BitWriter()
    out_glyphs = []
    for g in glyphs:
        w, h = g.get("box_w", 0), g.get("box_h", 0)
        if w == 0 or h == 0:
            out_glyphs.append({**g, "bitmap_index": 0, "adv_w": g.get("adv_w", 0) * 2})
            continue
        writer.align()
        start = len(writer.bytes)
        for row in glyph_bits(bitmap, g["bitmap_index"], w, h):
            for _ in range(2):
                for px in row:
                    writer.put(px)
                    writer.put(px)
        out_glyphs.append({
            "bitmap_index": start,
            "adv_w": g["adv_w"] * 2,
            "box_w": w * 2,
            "box_h": h * 2,
            "ofs_x": g.get("ofs_x", 0) * 2,
            "ofs_y": g.get("ofs_y", 0) * 2,
        })

    bmp_lines = []
    data = bytes(writer.bytes)
    for i in range(0, len(data), 16):
        bmp_lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    dsc_lines = [
        "    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},"
        % (g["bitmap_index"], g["adv_w"], g.get("box_w", 0), g.get("box_h", 0),
           g.get("ofs_x", 0), g.get("ofs_y", 0))
        for g in out_glyphs
    ]
    out = f"""/* Generated by tools/gen_font2x.py from {src_path.name}: every pixel doubled.
 * Do not edit by hand. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{chr(10).join(bmp_lines)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(dsc_lines)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = {range_start}, .range_length = {range_length}, .glyph_id_start = {glyph_id_start},
        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
    }}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 1,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height * 2},
    .base_line = {base_line * 2},
#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10
    .cap_height = 0,
    .x_height = 0,
#endif
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
#if LV_VERSION_CHECK(9, 3, 0)
    .static_bitmap = 1,
#endif
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(out)
    print(f"{name}: {len(out_glyphs)} glyphs, {len(data)} bitmap bytes, line height {line_height * 2}")


if __name__ == "__main__":
    main(sys.argv)
